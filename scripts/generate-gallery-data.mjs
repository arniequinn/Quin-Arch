// Writes src/data/galleryAssets.ts from source-material/gallery-build-report.json (made by
// build-gallery-assets.mjs): each published image's size, its thumbnail's size, its site title and
// its crop. Only published paths and site titles are written, never the source file names.
//
//   node scripts/generate-gallery-data.mjs
import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1")), "..");
const report = JSON.parse(fs.readFileSync(path.join(ROOT, "source-material", "gallery-build-report.json"), "utf8"));

const rows = report
  .filter((r) => r.size && r.thumbSize)
  .sort((a, b) => a.out.localeCompare(b.out))
  .map((r) => {
    const entry = {
      w: r.size[0],
      h: r.size[1],
      tw: r.thumbSize[0],
      th: r.thumbSize[1],
      ...(r.title ? { title: r.title } : {}),
      ...(r.crop ? { crop: r.crop } : {}),
    };
    return `  ${JSON.stringify(r.out)}: ${JSON.stringify(entry)},`;
  });

const out = `// Generated by scripts/generate-gallery-data.mjs — do not edit by hand.
// Every gallery image under public/portfolio/: native size (w × h), thumbnail size (tw × th, the
// WebP in public/portfolio/thumbs/ at the same path) and, where it was cropped from its source,
// the crop box [x, y, w, h] in source pixels.

export interface GalleryAsset {
  w: number;
  h: number;
  tw: number;
  th: number;
  title?: string;
  crop?: [number, number, number, number];
}

export const GALLERY_ASSETS: Record<string, GalleryAsset> = {
${rows.join("\n")}
};
`;
fs.writeFileSync(path.join(ROOT, "src", "data", "galleryAssets.ts"), out);
console.log(`${rows.length} assets written to src/data/galleryAssets.ts`);
