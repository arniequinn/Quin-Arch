// Writes one page per gallery project (documentation/v3.0-gallery-expansion.md §7) from
// src/data/projectPages.json:
//   projects/<slug>/index.html                 the HTML shell: title, meta, Open Graph, structured data
//   src/entries/project-<slug>-main.tsx        the entry that mounts GalleryProjectPage
// vite.config.ts picks up every projects/*/index.html, and vite-seo-plugin.ts prerenders it and
// lists it in sitemap.xml. Run again after changing projectPages.json:
//
//   node scripts/generate-project-pages.mjs
import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1")), "..");
const SITE = "https://quinarch.design";
const pages = JSON.parse(fs.readFileSync(path.join(ROOT, "src", "data", "projectPages.json"), "utf8"));

const esc = (s) => s.replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;");
const json = (v) => JSON.stringify(v, null, 2).replace(/\n/g, "\n    ");

for (const page of pages) {
  const url = `${SITE}/projects/${page.slug}/`;
  const image = `${SITE}/portfolio/${page.cover}`;
  const { width, height } = await sharp(path.join(ROOT, "public", "portfolio", page.cover)).metadata();
  const title = `${page.title} — ${page.kind}`;
  const description = `${page.summary} ${page.title}, by Quintessential Architecture.`;

  const ld = {
    "@context": "https://schema.org",
    "@graph": [
      {
        "@type": "CreativeWork",
        "@id": `${url}#work`,
        name: page.title,
        genre: page.kind,
        description: page.summary,
        url,
        image,
        creator: { "@type": "Person", "@id": `${SITE}/#arslan-qaiser`, name: "Arslan Qaiser", url: `${SITE}/design-philosophy/` },
        publisher: { "@type": "ProfessionalService", "@id": `${SITE}/#business`, name: "Quintessential Architecture", url: `${SITE}/` },
        isPartOf: { "@type": "CollectionPage", "@id": `${SITE}/projects/#collection`, url: `${SITE}/projects/` },
      },
      {
        "@type": "BreadcrumbList",
        itemListElement: [
          { "@type": "ListItem", position: 1, name: "Home", item: `${SITE}/` },
          { "@type": "ListItem", position: 2, name: "Project Library", item: `${SITE}/projects/` },
          { "@type": "ListItem", position: 3, name: page.title, item: url },
        ],
      },
    ],
  };

  const html = `<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0" />

    <!-- Generated by scripts/generate-project-pages.mjs from src/data/projectPages.json -->
    <title>${esc(title)} | Quintessential Architecture</title>
    <meta name="description" content="${esc(description)}" />
    <meta name="author" content="Arslan Qaiser, Quintessential Architecture" />
    <meta name="robots" content="index, follow, max-snippet:-1, max-image-preview:large, max-video-preview:-1" />
    <link rel="canonical" href="${url}" />
    <meta name="theme-color" content="#0a0a0a" />

    <link rel="icon" type="image/png" href="%BASE_URL%portfolio/quin-arch-logo.png" />
    <link rel="apple-touch-icon" href="%BASE_URL%portfolio/quin-arch-logo.png" />

    <meta property="og:locale" content="en_US" />
    <meta property="og:type" content="article" />
    <meta property="og:site_name" content="Quintessential Architecture" />
    <meta property="og:title" content="${esc(title)}" />
    <meta property="og:description" content="${esc(description)}" />
    <meta property="og:url" content="${url}" />
    <meta property="og:image" content="${image}" />
    <meta property="og:image:width" content="${width}" />
    <meta property="og:image:height" content="${height}" />
    <meta property="og:image:alt" content="${esc(page.title)}" />

    <meta name="twitter:card" content="summary_large_image" />
    <meta name="twitter:site" content="@quin_arch" />
    <meta name="twitter:title" content="${esc(title)}" />
    <meta name="twitter:description" content="${esc(description)}" />
    <meta name="twitter:image" content="${image}" />

    <link rel="preload" href="/fonts/dm-sans-latin.woff2" as="font" type="font/woff2" crossorigin>
    <link rel="preload" href="/fonts/cormorant-garamond-latin.woff2" as="font" type="font/woff2" crossorigin>

    <script type="application/ld+json">
    ${json(ld)}
    </script>
  </head>
  <body class="bg-neutral-950 text-neutral-100 antialiased selection:bg-amber-500 selection:text-neutral-950 font-sans">
    <div id="root"></div>
    <script type="module" src="/src/entries/project-${page.slug}-main.tsx"></script>
  </body>
</html>
`;

  const entry = `// Generated by scripts/generate-project-pages.mjs from src/data/projectPages.json
import { PageShell } from "../components/PageShell";
import { GalleryProjectPage } from "../pages/GalleryProjectPage";
import { projectBySlug } from "../data/galleryProjects";
import { mountPage } from "./mountPage";

const project = projectBySlug(${JSON.stringify(page.slug)})!;

export const render = mountPage((specialist) => (
  <PageShell specialist={specialist}>
    <GalleryProjectPage project={project} />
  </PageShell>
));
`;

  fs.mkdirSync(path.join(ROOT, "projects", page.slug), { recursive: true });
  fs.writeFileSync(path.join(ROOT, "projects", page.slug, "index.html"), html);
  fs.writeFileSync(path.join(ROOT, "src", "entries", `project-${page.slug}-main.tsx`), entry);
}
console.log(`${pages.length} project pages written.`);
